----
CREATE TABLE hv_templates (
  code     VARCHAR2(30)   NOT NULL,
  lang     VARCHAR2(2)    NOT NULL CONSTRAINT hv_templates_lang CHECK (lang IN ('en','sw')),
  body     VARCHAR2(1000) NOT NULL,
  CONSTRAINT hv_templates_pk PRIMARY KEY (code, lang)
)
----
CREATE TABLE hv_wards (
  ward_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  name     VARCHAR2(80) NOT NULL,
  county   VARCHAR2(80),
  lat      NUMBER(8,5)  NOT NULL,
  lon      NUMBER(8,5)  NOT NULL
)
----
-- R1-28: a plain UNIQUE (name, county) lets duplicates in when county is NULL; this index does not.
CREATE UNIQUE INDEX hv_wards_uk ON hv_wards (UPPER(name), NVL(county, '-'))
----
CREATE TABLE hv_places (
  place_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  ward_id  NUMBER NOT NULL CONSTRAINT hv_places_ward_fk REFERENCES hv_wards (ward_id),
  kind     VARCHAR2(10) NOT NULL CONSTRAINT hv_places_kind CHECK (kind IN ('stockist','warehouse','checkpoint')),
  name     VARCHAR2(120) NOT NULL,
  phone    VARCHAR2(30),
  active   NUMBER(1) DEFAULT 1 NOT NULL
)
----
CREATE TABLE hv_weather (
  ward_id    NUMBER NOT NULL CONSTRAINT hv_weather_ward_fk REFERENCES hv_wards (ward_id),
  wx_date    DATE   NOT NULL,
  temp_c     NUMBER NOT NULL,
  rh         NUMBER NOT NULL,
  rain_mm    NUMBER,
  rain_prob  NUMBER,
  fetched_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT hv_weather_pk PRIMARY KEY (ward_id, wx_date)
)
----
CREATE TABLE hv_weather_rain24 (
  ward_id    NUMBER NOT NULL CONSTRAINT hv_wx24_ward_fk REFERENCES hv_wards (ward_id),
  run_date   DATE   NOT NULL,
  rain_mm    NUMBER,
  rain_prob  NUMBER,
  fetched_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT hv_weather_rain24_pk PRIMARY KEY (ward_id, run_date)
)
----
-- R1-09: per ward fetch bookkeeping, written by harvestly_engine.record_weather_fetch (autonomous transaction)
CREATE TABLE hv_weather_fetch (
  ward_id         NUMBER NOT NULL CONSTRAINT hv_wxfetch_ward_fk REFERENCES hv_wards (ward_id),
  last_attempt_at TIMESTAMP WITH TIME ZONE,
  last_ok_at      TIMESTAMP WITH TIME ZONE,
  last_error      VARCHAR2(500),
  CONSTRAINT hv_weather_fetch_pk PRIMARY KEY (ward_id)
)
----
CREATE TABLE hv_batches (
  batch_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  farmer_ref      VARCHAR2(64),                       -- plaintext address, kept only to send; blanked by erase/retention (R1-11)
  farmer_hash     VARCHAR2(64),                       -- address_hash(addr): the identity used for matching (R1-11)
  channel         VARCHAR2(10) DEFAULT 'sms' NOT NULL CONSTRAINT hv_batches_channel CHECK (channel IN ('sms','telegram')),
  ward_id         NUMBER NOT NULL CONSTRAINT hv_batches_ward_fk REFERENCES hv_wards (ward_id),
  storage         VARCHAR2(10) NOT NULL CONSTRAINT hv_batches_storage CHECK (storage IN ('drying','sack','crib','floor','hermetic')),
  stored_since    DATE NOT NULL,
  lang            VARCHAR2(2) DEFAULT 'en' NOT NULL CONSTRAINT hv_batches_lang CHECK (lang IN ('en','sw')),
  bags            NUMBER(5) DEFAULT 1 NOT NULL,
  moisture        NUMBER,
  source          VARCHAR2(12) DEFAULT 'none' NOT NULL CONSTRAINT hv_batches_source CHECK (source IN ('none','salt_sticky','salt_flows','hygro','meter')),
  last_test       DATE,
  test_value      NUMBER,
  peak_since_test NUMBER,
  life_used       NUMBER DEFAULT 0 NOT NULL,
  last_advanced   DATE,
  last_alert      DATE,
  last_advice     VARCHAR2(20),
  told_level      VARCHAR2(8) DEFAULT 'UNKNOWN' NOT NULL,
  told_left       NUMBER,
  rain_unacked    NUMBER(3) DEFAULT 0 NOT NULL,
  status          VARCHAR2(8) DEFAULT 'active' NOT NULL CONSTRAINT hv_batches_status CHECK (status IN ('active','closed','stopped')),
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  last_run        DATE,                               -- daily_run idempotency: one run per batch per day (R1-05)
  ended_at        DATE,                               -- set when status becomes closed/stopped; retention clock
  CONSTRAINT hv_batches_moisture_src CHECK (moisture IS NULL OR source <> 'none')
)
----
CREATE INDEX hv_batches_farmer_ix ON hv_batches (channel, farmer_ref)
----
CREATE INDEX hv_batches_hash_ix ON hv_batches (channel, farmer_hash)
----
CREATE INDEX hv_batches_ward_ix ON hv_batches (ward_id, status)
----
-- R3 C3-02: the system-wide daily registration ceiling counts batches stored today
CREATE INDEX hv_batches_day_ix ON hv_batches (stored_since)
----
CREATE TABLE hv_messages (
  msg_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  batch_id     NUMBER CONSTRAINT hv_messages_batch_fk REFERENCES hv_batches (batch_id),
  msg_date     DATE NOT NULL,
  code         VARCHAR2(30) NOT NULL,
  kind         VARCHAR2(10) NOT NULL CONSTRAINT hv_messages_kind CHECK (kind IN ('PROACTIVE','REPLY')),
  lang         VARCHAR2(2) NOT NULL,
  body         VARCHAR2(1000) NOT NULL,
  body_other   VARCHAR2(1000),
  channel      VARCHAR2(10) NOT NULL,
  to_addr      VARCHAR2(64),                       -- plaintext only until sent/failed/cancelled, then blanked (R1-11)
  to_hash      VARCHAR2(64),                       -- address_hash(to_addr); used by the opt-out check
  status       VARCHAR2(10) DEFAULT 'QUEUED' NOT NULL CONSTRAINT hv_messages_status CHECK (status IN ('QUEUED','SENDING','SENT','FAILED','SKIPPED','CANCELLED')),
  attempts     NUMBER(2) DEFAULT 0 NOT NULL,
  created_at   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,   -- R2 C-08: compared with SYSTIMESTAMP
  sent_at      TIMESTAMP WITH TIME ZONE,                                  -- set when claimed (SENDING) and when sent
  provider_ref VARCHAR2(100),
  error_text   VARCHAR2(500),
  undo_last_alert   DATE,                         -- state to restore if the send finally fails (R1-08)
  undo_last_advice  VARCHAR2(20),
  undo_told_level   VARCHAR2(8),
  undo_told_left    NUMBER,
  undo_rain_unacked NUMBER
)
----
CREATE INDEX hv_messages_batch_ix ON hv_messages (batch_id, code, msg_date)
----
CREATE INDEX hv_messages_queue_ix ON hv_messages (status, created_at)
----
CREATE INDEX hv_messages_hash_ix ON hv_messages (to_hash)
----
-- R3 C3-02: the system-wide daily reply ceiling counts REPLY rows of the last day
CREATE INDEX hv_messages_reply_ix ON hv_messages (kind, created_at)
----
-- R1-05: at most one PROACTIVE message per batch per day. Non-PROACTIVE rows give (NULL, NULL) and are not indexed.
CREATE UNIQUE INDEX hv_messages_pro_uk ON hv_messages (CASE WHEN kind = 'PROACTIVE' THEN batch_id END, CASE WHEN kind = 'PROACTIVE' THEN msg_date END)
----
CREATE TABLE hv_inbound (
  in_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  batch_id   NUMBER CONSTRAINT hv_inbound_batch_fk REFERENCES hv_batches (batch_id),
  channel    VARCHAR2(10) NOT NULL,
  from_hash  VARCHAR2(64),                         -- address_hash only; never the plaintext address (R1-11)
  rcv_date   DATE NOT NULL,
  raw_text   VARCHAR2(1000),                       -- known senders only; blanked after 30 days (R1-11)
  norm_text  VARCHAR2(1000),
  cmd        VARCHAR2(20),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
----
CREATE INDEX hv_inbound_batch_ix ON hv_inbound (batch_id, rcv_date)
----
CREATE INDEX hv_inbound_hash_ix ON hv_inbound (from_hash)
----
-- R1-03: phone-wide opt-out (STOP / START); checked when queueing and when claiming messages to send
CREATE TABLE hv_optout (
  addr_hash VARCHAR2(64) NOT NULL,
  opted_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT hv_optout_pk PRIMARY KEY (addr_hash)
)
----
-- R2 C-05: replay/duplicate protection. One row per provider message id (Africa's Talking `id`, Telegram `update_id`).
-- The primary key makes the check atomic; a failed request rolls its row back so the provider's retry is processed.
CREATE TABLE hv_inbound_seen (
  channel     VARCHAR2(10)  NOT NULL,
  provider_id VARCHAR2(100) NOT NULL,
  seen_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT hv_inbound_seen_pk PRIMARY KEY (channel, provider_id)
)
----
-- R2 C-05: per phone per hour counter of inbound messages (hash only, never the number)
CREATE TABLE hv_rate (
  addr_hash   VARCHAR2(64) NOT NULL,
  bucket_hour DATE         NOT NULL,
  n           NUMBER(6)    DEFAULT 0 NOT NULL,
  CONSTRAINT hv_rate_pk PRIMARY KEY (addr_hash, bucket_hour)
)
----
CREATE TABLE hv_config (
  cfg_key    VARCHAR2(60) PRIMARY KEY,
  cfg_value  VARCHAR2(1000) NOT NULL,
  note       VARCHAR2(200)
)
----
CREATE TABLE hv_run_log (
  log_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  batch_id        NUMBER NOT NULL,
  run_date        DATE NOT NULL,
  risk            VARCHAR2(8),
  days_left       NUMBER,
  moisture        NUMBER,
  life_used_pct   NUMBER,
  advice          VARCHAR2(20),
  code            VARCHAR2(30),
  flags           VARCHAR2(500),
  error_text      VARCHAR2(500),
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT hv_run_log_uk UNIQUE (batch_id, run_date)
)
----
CREATE INDEX hv_run_log_ix ON hv_run_log (run_date, batch_id)
