-- Harvestly schema DDL (source for ../schema.sql; statements are separated by lines of "----").
-- Oracle 19c / 23ai Always Free compatible (identity columns, no 23ai-only syntax).
--
-- hv_config keys (cfg_key -> meaning). Prefer APEX Web Credentials for secrets where you can (R1-11/R1-14):
--   telegram_secret    header X-Telegram-Bot-Api-Secret-Token for POST /hv/telegram     (R1-14: one secret per endpoint)
--   sms_secret         path secret in POST /hv/sms/:secret
--   ussd_secret        path secret in POST /hv/ussd/:secret
--   hash_pepper        HMAC key for address_hash (phone / chat id); long random string; losing it orphans all hashes
--   at_ip_allowlist    comma list of Africa's Talking callback source IPs. MANDATORY (R2 C-05): missing or empty = every
--                      SMS/USSD callback is refused (403). The literal value DISABLED turns the check off (sandbox only).
--   trusted_proxies    comma list of proxy/load-balancer IPs allowed to set X-Forwarded-For (R2 C-13); default none
--   max_in_per_hour    inbound messages processed per phone per hour (default 12; STOP is never limited)
--   max_reply_per_hour / max_reply_per_day   queued replies per phone (defaults 6 / 20; the STOP confirmation is exempt)
--   max_howto_per_day  how-to replies to unknown senders, whole system, per day (default 300)
--   max_batches_per_day  batches one phone may register per day (default 3)
--   telegram_bot_token Telegram Bot API token (used inside hv_send_one only; Bot API forces it into the URL path, see ords_handlers.sql section 4)
--   at_username, at_api_key, at_sender_id (optional), at_base_url (default https://api.africastalking.com)
-- The old single key webhook_secret is no longer read.
