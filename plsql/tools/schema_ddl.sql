CREATE TABLE hv_ast (
  temp_f   NUMBER(5,1) NOT NULL,
  mc       NUMBER(5,1) NOT NULL,
  days     NUMBER(8,1) NOT NULL,
  CONSTRAINT hv_ast_pk PRIMARY KEY (temp_f, mc)
