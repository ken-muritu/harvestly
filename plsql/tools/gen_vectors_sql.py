#!/usr/bin/env python3
"""Generate ../vectors_data.sql from ../../engine/vectors.json.

    python3 gen_vectors_sql.py

vectors.json stores the traces but not the weather (it says "see make_vectors.py"), so the three
weather rules are copied here and CHECKED against the vectors by replaying them through the Python
reference engine (engine/make_vectors.scenario). If the copy ever drifts, this script fails.
Output: plain tables hv_vec_* (dropped and re-created on every run of vectors_data.sql).
"""
import json
import os
import sys
from datetime import date, timedelta

HERE = os.path.dirname(os.path.abspath(__file__))
ENGINE = os.path.join(HERE, "..", "..", "engine")
sys.path.insert(0, ENGINE)
import make_vectors as MV  # noqa: E402

D0 = MV.D0


def demo_wx(issued_off, k):   # same rule as make_vectors.main(): wet spell appears in the day-3 forecast
    if 4 <= k <= 11 and issued_off >= 3:
        return (18.0, 88.0, 12.0 if k == 9 else 0.0, 80.0 if k == 9 else 20.0)
    return (18.0, 63.0, 0.0, 10.0)


WX = {
    "demo_pitch": demo_wx,
    "salt_pass_then_seal": lambda issued_off, k: (18.0, 70.0, 0.0, 10.0),
    "dry_grain_rewets": lambda issued_off, k: (19.0, 92.0, 0.0, 10.0),
}


def lit(x):
    if x is None:
        return "NULL"
    if isinstance(x, str):
        return "'" + x.replace("'", "''") + "'"
    return repr(x)


def lit_u(x):
    """String literal that survives any client character set: non-ASCII characters become UNISTR escapes."""
    if x is None:
        return "NULL"
    if all(ord(c) < 128 for c in x):
        return lit(x)
    parts, run = [], ""
    for c in x:
        if ord(c) < 128:
            run += c
        else:
            if run:
                parts.append("'" + run.replace("'", "''") + "'")
                run = ""
            for u in c.encode("utf-16-be").hex(" ", 2).split():
                parts.append("UNISTR('\\" + u + "')")
    if run:
        parts.append("'" + run.replace("'", "''") + "'")
    return " || ".join(parts)


def verify(vec):
    """Replay with the reference engine using OUR weather copy; must equal vectors.json."""
    for sc in vec["scenarios"]:
        wx = WX[sc["name"]]
        replies = {}
        for t in sc["trace"]:
            if t["event"] == "reply":
                off = (date.fromisoformat(t["day"]) - D0).days
                replies.setdefault(off, []).append(t["text"])
        mine = MV.scenario(sc["name"], sc["storage"], sc["days"],
                           lambda issued, d: wx((issued - D0).days, (d - D0).days), replies)
        assert mine["trace"] == sc["trace"], f"weather copy drifted for {sc['name']}"


def main():
    vec = json.load(open(os.path.join(ENGINE, "vectors.json")))
    verify(vec)
    out = ["-- GENERATED by tools/gen_vectors_sql.py from engine/vectors.json - do not edit.",
           "SET DEFINE OFF", ""]
    for tab in ("hv_vec_emc", "hv_vec_ast", "hv_vec_scn", "hv_vec_wx", "hv_vec_trace", "hv_vec_round", "hv_vec_evid",
                "hv_vec_optout", "hv_vec_norm", "hv_vec_addr", "hv_vec_cfg", "hv_vec_dl", "hv_vec_dlf"):
        out.append(f"BEGIN EXECUTE IMMEDIATE 'DROP TABLE {tab} PURGE'; "
                   "EXCEPTION WHEN OTHERS THEN IF SQLCODE <> -942 THEN RAISE; END IF; END;\n/")
    out += [
        "CREATE TABLE hv_vec_emc (temp_c NUMBER, rh NUMBER, emc NUMBER);",
        "CREATE TABLE hv_vec_ast (temp_c NUMBER, mc NUMBER, days NUMBER);",
        "CREATE TABLE hv_vec_scn (scn VARCHAR2(40), storage VARCHAR2(10), start_date DATE, n_days NUMBER, ord NUMBER);",
        "CREATE TABLE hv_vec_wx (scn VARCHAR2(40), issued_off NUMBER, day_off NUMBER, temp_c NUMBER, rh NUMBER, rain_mm NUMBER, rain_prob NUMBER);",
        "CREATE TABLE hv_vec_trace (scn VARCHAR2(40), seq NUMBER, day_off NUMBER, event VARCHAR2(10), txt VARCHAR2(100),"
        " cmd VARCHAR2(20), code VARCHAR2(30), risk VARCHAR2(8), days_left NUMBER, moisture NUMBER, life_pct NUMBER,"
        " msg VARCHAR2(1000), moisture_s VARCHAR2(20), life_s VARCHAR2(20), moisture_exact NUMBER, life_exact NUMBER);",
        "CREATE TABLE hv_vec_round (x NUMBER, f0 VARCHAR2(20), f1 VARCHAR2(20), f2 VARCHAR2(20));",
        "CREATE TABLE hv_vec_evid (reading NUMBER, en VARCHAR2(100), sw VARCHAR2(100));",
        "CREATE TABLE hv_vec_optout (seq NUMBER, txt VARCHAR2(200), norm VARCHAR2(200), optout NUMBER);",
        "CREATE TABLE hv_vec_norm (text_len NUMBER, norm_len NUMBER);",
        "CREATE TABLE hv_vec_addr (addr VARCHAR2(100), canonical VARCHAR2(100), hash VARCHAR2(64));",
        "CREATE TABLE hv_vec_cfg (k VARCHAR2(30), v VARCHAR2(200));",
        "CREATE TABLE hv_vec_dl (id NUMBER, storage VARCHAR2(10), moisture NUMBER, life NUMBER, left_days NUMBER, lvl VARCHAR2(8));",
        "CREATE TABLE hv_vec_dlf (id NUMBER, seq NUMBER, temp_c NUMBER, rh NUMBER);",
        "",
    ]
    for r in vec["emc"]:
        out.append(f"INSERT INTO hv_vec_emc VALUES ({lit(r['temp_c'])}, {lit(r['rh'])}, {lit(r['emc'])});")
    for r in vec["ast"]:
        out.append(f"INSERT INTO hv_vec_ast VALUES ({lit(r['temp_c'])}, {lit(r['mc'])}, {lit(r['days'])});")
    for n, sc in enumerate(vec["scenarios"], 1):
        out.append(f"INSERT INTO hv_vec_scn VALUES ({lit(sc['name'])}, {lit(sc['storage'])}, "
                   f"DATE '{sc['start']}', {sc['days']}, {n});")
        wx = WX[sc["name"]]
        for o in range(sc["days"]):
            for k in range(-2, 8):                      # as issued on day o: today-2 .. today+7
                t, rh, mm, pp = wx(o, o + k)
                out.append(f"INSERT INTO hv_vec_wx VALUES ({lit(sc['name'])}, {o}, {o + k}, "
                           f"{lit(t)}, {lit(rh)}, {lit(mm)}, {lit(pp)});")
        for seq, t in enumerate(sc["trace"], 1):
            off = (date.fromisoformat(t["day"]) - D0).days
            if t["event"] == "reply":
                out.append(f"INSERT INTO hv_vec_trace (scn, seq, day_off, event, txt, cmd, code, msg) VALUES "
                           f"({lit(sc['name'])}, {seq}, {off}, 'reply', {lit(t['text'])}, {lit(t['cmd'])}, {lit(t['code'])}, "
                           f"{lit(t['message'])});")
            else:
                out.append(f"INSERT INTO hv_vec_trace (scn, seq, day_off, event, code, risk, days_left, moisture, life_pct,"
                           f" msg, moisture_s, life_s, moisture_exact, life_exact) VALUES "
                           f"({lit(sc['name'])}, {seq}, {off}, 'evening', {lit(t['code'])}, {lit(t['level'])}, "
                           f"{lit(t['days_left'])}, {lit(t['moisture'])}, {lit(t['life_used_pct'])}, {lit(t['message'])}, "
                           f"{lit(t['moisture_s'])}, {lit(t['life_used_pct_s'])}, {lit(t['moisture_exact'])}, "
                           f"{lit(t['life_used_exact'])});")
    for r in vec["rounding"]:
        out.append(f"INSERT INTO hv_vec_round VALUES ({lit(r['x'])}, {lit(r.get('fmt0'))}, {lit(r.get('fmt1'))}, {lit(r.get('fmt2'))});")
    for r in vec["evidence"]:
        out.append(f"INSERT INTO hv_vec_evid VALUES ({lit(r['reading'])}, {lit(r['en'])}, {lit(r['sw'])});")
    for n, r in enumerate(vec["optout"], 1):
        out.append(f"INSERT INTO hv_vec_optout VALUES ({n}, {lit_u(r['text'])}, {lit_u(r['norm'])}, {1 if r['optout'] else 0});")
    for r in vec["normalise"]:
        out.append(f"INSERT INTO hv_vec_norm VALUES ({r['text_len']}, {r['norm_len']});")
    out.append(f"INSERT INTO hv_vec_cfg VALUES ('pepper', {lit(vec['pepper'])});")
    for r in vec["addresses"]:
        out.append(f"INSERT INTO hv_vec_addr VALUES ({lit_u(r['addr'])}, {lit_u(r['canonical'])}, {lit(r['hash'])});")
    for i, r in enumerate(vec["days_left_cases"], 1):
        out.append(f"INSERT INTO hv_vec_dl VALUES ({i}, {lit(r['storage'])}, {lit(r['moisture'])}, {lit(r['life'])}, "
                   f"{lit(r['left'])}, {lit(r['level'])});")
        for k, (tc, rh) in enumerate(r["forecast"], 1):
            out.append(f"INSERT INTO hv_vec_dlf VALUES ({i}, {k}, {lit(tc)}, {lit(rh)});")
    out.append("COMMIT;")
    path = os.path.join(HERE, "..", "vectors_data.sql")
    open(path, "w").write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(path), len(out), "lines")


if __name__ == "__main__":
    main()
